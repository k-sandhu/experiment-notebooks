"""Bind packaged tests and independent metadata review before one continuation."""
from datetime import datetime, timezone
import hashlib
import json
from pathlib import Path

from scale_intervention_resume_003 import scale_intervention_resume_003_verify


BASE = Path(__file__).resolve().parent
ROOT = BASE.parent / 'experiment_notebooks/notebooks/23-synthetic-data-curation'
DATA = ROOT / 'data/scale_v5'
PUBLIC = DATA / 'intervention_resume_003'


def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def read(path):
    return json.loads(path.read_text(encoding='utf-8'))


def main():
    gate_path = PUBLIC / 'continuation_start_003.json'
    correction = None
    if gate_path.exists():
        gate = read(gate_path)
        generated = {name: expected for name, expected in gate['sha256'].items()
                     if '__pycache__' in Path(name).parts or Path(name).suffix == '.pyc'}
        if not generated:
            assert all(sha(DATA / name) == expected for name, expected in gate['sha256'].items())
            print(json.dumps({'existing_gate_verified': True, 'sha256': sha(gate_path), 'model_calls': 0}))
            return
        assert sha(gate_path) == '9f8dc950c83fba7293f15f80873a2c3427d8ff798827eba19147d64736fae4d4'
        assert not (DATA / 'main/manifest.json').exists()
        assert not list((DATA / 'main').glob('intervention_resume_003_start_*.json'))
        correction = {'model_calls': 0, 'efficacy_reads': False,
            'corrected_before_live_continuation': True, 'initial_gate_sha256': sha(gate_path),
            'initial_gate_exact_utf8': gate_path.read_text(encoding='utf-8'),
            'removed_generated_bindings': generated,
            'reason': 'The uncommitted pre-call gate included Python bytecode created by packaged tests. Exclude generated bytecode, retain all study/source/log bindings, and explicitly stage the log files ignored by the generic repository rule. No amendment, source task, raw response, selection or analysis changed.'}
        target = PUBLIC / 'pre_call_gate_packaging_correction.json'
        with target.open('x', encoding='utf-8', newline='\n') as stream:
            json.dump(correction, stream, sort_keys=True, ensure_ascii=False, indent=2)
            stream.write('\n')
    state = scale_intervention_resume_003_verify(ROOT, PUBLIC / 'amendment_003.json')
    review = read(BASE / 'scale_intervention_resume_003_preflight.json')
    assert review['passed'] is True and review['model_calls'] == 0
    assert review['amendment_sha256'] == state['amendment_sha256'], 'Preflight covers a different amendment'
    assert review.get('efficacy_reads', False) is False
    assert not (DATA / 'main/manifest.json').exists()
    assert not list((DATA / 'main').glob('intervention_resume_003_start_*.json')), 'Live continuation already started'
    names = ('scale_intervention_resume_003_preflight.json', 'scale_intervention_resume_003_preflight.md',
             'scale_intervention_resume_003_packaged_unit_tests.log',
             'scale_missing_outcomes_003_packaged_unit_tests.log')
    for name in names:
        source, target = BASE / name, PUBLIC / name
        if name.endswith('_tests.log'):
            text = source.read_text(encoding='utf-8')
            assert '\nOK\n' in text and 'FAILED' not in text
        raw = source.read_bytes()
        assert not target.exists() or target.read_bytes() == raw, 'Existing preflight artifact differs'
        if not target.exists():
            with target.open('xb') as stream:
                stream.write(raw)
    source_target = PUBLIC / 'source_snapshot' / Path(__file__).name
    if correction:
        assert sha(source_target) == gate['sha256'][source_target.relative_to(DATA).as_posix()]
        source_target.write_bytes(Path(__file__).read_bytes())
    else:
        assert not source_target.exists() or source_target.read_bytes() == Path(__file__).read_bytes()
    if not source_target.exists():
        with source_target.open('xb') as stream:
            stream.write(Path(__file__).read_bytes())
    bindings = dict(read(DATA / 'intervention_start_declaration.json')['sha256'])
    for path in sorted(PUBLIC.rglob('*')):
        if path.is_file() and path != gate_path and '__pycache__' not in path.parts and path.suffix != '.pyc':
            bindings[path.relative_to(DATA).as_posix()] = sha(path)
    assert all(sha(DATA / name) == expected for name, expected in bindings.items())
    gate = {'protocol': '23-scale-v5', 'phase': 'second_interruption_continuation',
            'declared_at_utc': datetime.now(timezone.utc).isoformat(),
            'amendment_sha256': state['amendment_sha256'], 'model_calls': 0,
            'efficacy_reads': False, 'recorded_raw_caches_preserved': len(state['inventory']),
            'unavailable_request_keys': sorted(state['approved']), 'unsent_jobs': 780,
            'sha256': bindings,
            'scope': 'One reviewed continuation of only unsent frozen requests; no recorded key repeated. No efficacy inspected.'}
    with gate_path.open('w' if correction else 'x', encoding='utf-8', newline='\n') as stream:
        json.dump(gate, stream, sort_keys=True, ensure_ascii=False, indent=2)
        stream.write('\n')
    print(json.dumps({'passed': True, 'bindings': len(bindings), 'sha256': sha(gate_path),
                      'amendment_sha256': state['amendment_sha256'], 'model_calls': 0}))


if __name__ == '__main__':
    main()
